# pizzas.py

# Menyimpan tiga jenis pizza favorit ke dalam list
pizzas = ["Pepperoni", "Meat Lovers", "Cheese Pizza"]

# Menggunakan for loop untuk mencetak pernyataan tentang setiap pizza
for pizza in pizzas:
    print(f"Saya sangat suka {pizza} pizza.")

# Pernyataan umum di luar for loop (hanya dicetak sekali di akhir)
print("\nPizza adalah salah satu makanan favorit saya sepanjang masa.")
print("Saya benar-benar sangat mencintai pizza!")