# animals.py

# Menyimpan tiga hewan yang memiliki karakteristik serupa (hewan peliharaan/mamalia berbulu)
animals = ["Kucing", "Anjing", "Kelinci"]

# Menggunakan for loop untuk mencetak pernyataan tentang masing-masing hewan
for animal in animals:
    print(f"Seekor {animal.lower()} akan menjadi hewan peliharaan yang luar biasa.")

# Pernyataan di luar for loop yang merangkum kesamaan mereka
print("\nHewan-hewan ini memiliki sifat yang ramah kepada manusia.")
print("Hewan apa pun dari daftar ini akan menjadi teman peliharaan yang hebat!")