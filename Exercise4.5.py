# summing_a_million.py

# Membuat list dari 1 hingga 1.000.000
numbers = list(range(1, 1000001))

# Memeriksa batas bawah dan batas atas list
print(f"Nilai minimum: {min(numbers)}")
print(f"Nilai maksimum: {max(numbers)}")

# Menjumlahkan seluruh angka dari 1 hingga 1.000.000 secara instan
print(f"Jumlah total keseluruhan: {sum(numbers)}")