# Versi 1: Menjalankan blok 'if' (Alien hijau)
alien_color = 'green'

if alien_color == 'green':
    print("Anda baru saja mendapatkan 5 poin karena menembak alien.")
else:
    print("Anda baru saja mendapatkan 10 poin.")

# Versi 2: Menjalankan blok 'else' (Alien non-hijau, misal: kuning)
alien_color = 'yellow'

if alien_color == 'green':
    print("Anda baru saja mendapatkan 5 poin karena menembak alien.")
else:
    print("Anda baru saja mendapatkan 10 poin.")