# Membuat dictionary untuk menyimpan informasi seseorang
person = {
    'first_name': 'Budi',
    'last_name': 'Santoso',
    'age': 25,
    'city': 'Jakarta'
}

# Mencetak setiap informasi
print(f"Nama Depan: {person['first_name']}")
print(f"Nama Belakang: {person['last_name']}")
print(f"Usia: {person['age']}")
print(f"Kota Tempat Tinggal: {person['city']}")